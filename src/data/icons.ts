/** Label for an icon name, falling back to a title-cased slug. */
export function iconLabel(name: string): string {
  if (ICON_LABELS[name]) return ICON_LABELS[name];
  return name
    .replace(/^brand-/, '')
    .split(/[-.]/)
    .map((w) => w.charAt(0).toUpperCase() + w.slice(1))
    .join(' ');
}
